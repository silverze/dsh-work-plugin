#!/usr/bin/env node
/**
 * Generate profiles/work/dev.patch.yml with the absolute path to the bundle.
 * Absolute paths are required by the DSH loader; keeping this generated avoids
 * committing machine-specific paths.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const bundle = join(root, 'packages', 'bundle', 'index.js')
const host = join(root, 'packages', 'host-work', 'lib', 'index.js')
// The bundle's own cordis.patch.yml only expands in bundle mode (profile
// `dsh.profile.bundles`), so the dev patch has to insert the client plugin
// explicitly — otherwise no client UI (chips, workbench panel) loads.
const client = join(root, 'packages', 'client-work', 'lib', 'index.js')
const feishu = join(root, 'packages', 'host-feishu', 'lib', 'index.js')
const smoke = join(root, 'scripts', 'smoke-preset.mjs')
const smokeSkills = join(root, 'scripts', 'smoke-skills.mjs')
const smokeRemote = join(root, 'scripts', 'smoke-remote.mjs')
const smokePresetSkills = join(root, 'scripts', 'smoke-preset-skills.mjs')
const primaryRuntime = process.env.DSH_PRIMARY_RUNTIME
const officeRow = primaryRuntime
  ? `    - id: acme-skill-office\n      name: '@deepseek-ai/dsh-skill-office'\n      config:\n        assetRoot: '${join(primaryRuntime, '..', 'office-skills').replaceAll("'", "''")}'\n        node: '${join(primaryRuntime, 'dependencies', 'node', 'bin', 'node').replaceAll("'", "''")}'\n`
  : ''
const skillsPlugin = join(root, 'packages', 'skills-work', 'index.js')
const workSkillsRow = `    - id: work-skills\n      name: '${skillsPlugin.replaceAll("'", "''")}'\n`
const target = join(root, 'profiles', 'work', 'dev.patch.yml')
const preset = readFileSync(join(root, 'packages', 'bundle', 'presets', 'work.patch.yml'), 'utf8')
const presetWithSmoke = preset.replace(
  "          - id: tool-skill\n            name: '@deepseek-ai/dsh-tool-skill'",
  "          - id: tool-skill\n            name: '@deepseek-ai/dsh-tool-skill'\n          - id: acme-smoke-preset-skills\n            name: '" + smokePresetSkills.replaceAll("'", "''") + "'",
)

const yaml = `# Generated by scripts/render-dev-patch.mjs — do not commit.
- insert:
    - id: dsh-work-bundle
      name: '${bundle.replaceAll("'", "''")}'
    - id: dsh-work-host
      name: '${host.replaceAll("'", "''")}'
    - id: dsh-work-client
      name: '${client.replaceAll("'", "''")}'
${officeRow}${workSkillsRow}    - id: dsh-work-feishu
      name: '${feishu.replaceAll("'", "''")}'
      config:
        accessTokenEnv: FEISHU_USER_ACCESS_TOKEN
    - id: acme-smoke-preset
      name: '${smoke.replaceAll("'", "''")}'
    - id: acme-smoke-skills
      name: '${smokeSkills.replaceAll("'", "''")}'
    - id: acme-smoke-remote
      name: '${smokeRemote.replaceAll("'", "''")}'

${presetWithSmoke}`

mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, yaml, 'utf8')
console.log(`wrote ${target}`)
console.log(`plugin: ${bundle}`)
console.log('next: dsh --profile web --patch ./profiles/work/dev.patch.yml --no-open')
